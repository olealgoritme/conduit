# embed.sh OUT NAME FILE [NAME FILE ...]
#
# Turns shader sources into C string constants (static const char NAME[])
# for nb_gpuscale.c, which hands them to glShaderSource as they are.
#
# The AMD FidelityFX headers (third_party/fsr1, third_party/cas) are vendored
# unmodified.  Their constant-setup functions assign int literals to uint
# vector components, which desktop GLSL converts implicitly and GLSL ES does
# not; the four substitutions below add the `u` suffix, and touch nothing else
# (no other source here contains these exact statements).
set -eu
out=$1
shift
tmp=$out.tmp
{
    echo "/* Generated by shaders/embed.sh from the files named below; do not edit. */"
    while [ $# -ge 2 ]; do
        name=$1
        file=$2
        shift 2
        echo "/* $file */"
        echo "static const char $name[] ="
        tr -d '\r' < "$file" |
        sed -e 's/con3\[2\]=con3\[3\]=0;/con3[2]=con3[3]=0u;/' \
            -e 's/con\[2\]=0;/con[2]=0u;/' \
            -e 's/con\[3\]=0;/con[3]=0u;/' \
            -e 's/const1\[3\]=0;/const1[3]=0u;/' \
            -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/"/' -e 's/$/\\n"/'
        echo ";"
    done
} > "$tmp"
mv "$tmp" "$out"
