//! NVKMS command numbers, per release.
//!
//! `/dev/nvidia-modeset` takes every operation through one ioctl number; the
//! operation is the first word of the request, an index into
//! `enum NvKmsIoctlCommand`. NVKMS is the host's real display driver and the
//! compositor shares it, so the backend serves a guest only what buffer
//! sharing needs and refuses everything that would act on the host's monitors.
//! Naming those commands takes their numbers, and the numbers move: entries are
//! added in the middle of the enum, so REGISTER_SURFACE is 16 on 535.129.03,
//! 17 on 580.178.04 and 16 on 615.71.09, and ENABLE_VBLANK_SEM_CONTROL is
//! absent on 535, 60 on 565.77, 61 on 580.178.04 and 60 on 595.
//!
//! One rule: **a command's identity is this table's entry for the host's
//! release, and no caller adds to or subtracts from one command to find
//! another.** A release without a table of its own has no entry here
//! ([`select`] answers `None` for it, never a neighbour's), and the caller
//! then serves only [`FIRST_COMMANDS`].
//!
//! Generated by `gen/nvkms_extract.py` from each release's `nvkms-api.h`.

pub mod v535_129_03;
pub mod v565_77_00;
pub mod v580_178_04;
pub mod v595_104_02;
pub mod v595_71_05;
pub mod v610_57_04;
pub mod v615_71_09;

use crate::version::DriverVersion;

/// The commands every release numbers the same, and the only ones served on a
/// release with no table: `ALLOC_DEVICE` and `FREE_DEVICE`, the first two
/// entries of the enum since NVKMS's first release.
pub const FIRST_COMMANDS: [u32; 2] = [0, 1];

/// One release's numbers for the commands the backend names.
#[derive(Debug)]
pub struct Commands {
    pub alloc_device: u32,
    pub free_device: u32,
    pub query_disp: u32,
    pub register_surface: u32,
    pub unregister_surface: u32,
    pub grant_surface: u32,
    pub acquire_surface: u32,
    pub release_surface: u32,
    /// `None` where the release has no such command (535).
    pub enable_vblank_sem_control: Option<u32>,
    pub disable_vblank_sem_control: Option<u32>,
    /// Every command of the release, by name without the `NVKMS_IOCTL_`
    /// prefix, in enum order.
    pub all: &'static [(&'static str, u32)],
}

/// What a guest may do through NVKMS, as the backend decides it.
#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum Verdict {
    /// Forward to the host: device allocation and the surface commands.
    Forward,
    /// Forward, and the request carries a descriptor to translate
    /// (REGISTER_SURFACE).
    ForwardWithFd,
    /// QUERY_DISP: answered with a display that has nothing wired to it.
    AnswerQueryDisp,
    /// Success, answered here; `reply_handle` says whether to write the handle
    /// ENABLE_VBLANK_SEM_CONTROL returns.
    AnswerVblank { reply_handle: bool },
    /// Refused: it acts on the host's display.
    Refuse,
}

impl Commands {
    /// What to do with command number `cmd`.
    pub fn verdict(&self, cmd: u32) -> Verdict {
        if cmd == self.register_surface {
            Verdict::ForwardWithFd
        } else if cmd == self.alloc_device
            || cmd == self.free_device
            || [
                self.unregister_surface,
                self.grant_surface,
                self.acquire_surface,
                self.release_surface,
            ]
            .contains(&cmd)
        {
            Verdict::Forward
        } else if cmd == self.query_disp {
            Verdict::AnswerQueryDisp
        } else if Some(cmd) == self.enable_vblank_sem_control {
            Verdict::AnswerVblank { reply_handle: true }
        } else if Some(cmd) == self.disable_vblank_sem_control {
            Verdict::AnswerVblank {
                reply_handle: false,
            }
        } else {
            Verdict::Refuse
        }
    }
}

/// The table for exactly `v`, or `None`.
pub fn select(v: DriverVersion) -> Option<&'static Commands> {
    PROFILES.iter().find(|(pv, _)| *pv == v).map(|(_, c)| *c)
}

/// What to do with command `cmd` on release `v`: its table's verdict, or on a
/// release with none, [`FIRST_COMMANDS`] forwarded and everything else refused.
pub fn verdict(v: Option<DriverVersion>, cmd: u32) -> Verdict {
    match v.and_then(select) {
        Some(c) => c.verdict(cmd),
        None if FIRST_COMMANDS.contains(&cmd) => Verdict::Forward,
        None => Verdict::Refuse,
    }
}

/// Profiles in ascending version order.
static PROFILES: &[(DriverVersion, &Commands)] = &[
    (DriverVersion::new(535, 129, 3), &v535_129_03::COMMANDS),
    (DriverVersion::new(565, 77, 0), &v565_77_00::COMMANDS),
    (DriverVersion::new(580, 178, 4), &v580_178_04::COMMANDS),
    (DriverVersion::new(595, 71, 5), &v595_71_05::COMMANDS),
    (DriverVersion::new(595, 104, 2), &v595_104_02::COMMANDS),
    (DriverVersion::new(610, 57, 4), &v610_57_04::COMMANDS),
    (DriverVersion::new(615, 71, 9), &v615_71_09::COMMANDS),
];

/// The versions with a table of their own, ascending.
pub fn supported_versions() -> impl Iterator<Item = DriverVersion> {
    PROFILES.iter().map(|(v, _)| *v)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn all() -> impl Iterator<Item = (DriverVersion, &'static Commands)> {
        PROFILES.iter().copied()
    }

    #[test]
    fn profiles_are_in_ascending_order() {
        assert!(PROFILES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    /// The table is the enum: every command numbered 0..N once, and the named
    /// fields are entries of it.
    #[test]
    fn the_named_commands_are_entries_of_the_enum() {
        for (v, c) in all() {
            for (i, (_, n)) in c.all.iter().enumerate() {
                assert_eq!(*n as usize, i, "{v}");
            }
            let named = |name: &str| c.all.iter().find(|(k, _)| *k == name).map(|(_, n)| *n);
            assert_eq!(named("ALLOC_DEVICE"), Some(c.alloc_device), "{v}");
            assert_eq!(named("FREE_DEVICE"), Some(c.free_device), "{v}");
            assert_eq!(named("QUERY_DISP"), Some(c.query_disp), "{v}");
            assert_eq!(named("REGISTER_SURFACE"), Some(c.register_surface), "{v}");
            assert_eq!(
                named("UNREGISTER_SURFACE"),
                Some(c.unregister_surface),
                "{v}"
            );
            assert_eq!(named("GRANT_SURFACE"), Some(c.grant_surface), "{v}");
            assert_eq!(named("ACQUIRE_SURFACE"), Some(c.acquire_surface), "{v}");
            assert_eq!(named("RELEASE_SURFACE"), Some(c.release_surface), "{v}");
            assert_eq!(
                named("ENABLE_VBLANK_SEM_CONTROL"),
                c.enable_vblank_sem_control,
                "{v}"
            );
            assert_eq!(
                named("DISABLE_VBLANK_SEM_CONTROL"),
                c.disable_vblank_sem_control,
                "{v}"
            );
        }
    }

    /// The served set is the one the backend has always served: the first two
    /// commands, and REGISTER..RELEASE (five consecutive), never a modeset.
    #[test]
    fn the_surface_commands_are_five_in_a_row_after_register() {
        for (v, c) in all() {
            assert_eq!(
                [c.alloc_device, c.free_device, c.query_disp],
                [0, 1, 2],
                "{v}"
            );
            assert_eq!(
                [
                    c.unregister_surface,
                    c.grant_surface,
                    c.acquire_surface,
                    c.release_surface
                ],
                [
                    c.register_surface + 1,
                    c.register_surface + 2,
                    c.register_surface + 3,
                    c.register_surface + 4
                ],
                "{v}"
            );
        }
    }

    /// What 565.77 got wrong: ENABLE is 60, DISABLE 61 and the fliplock group
    /// 59, which the old `register_surface + 43` landed on.
    #[test]
    fn vblank_commands_resolve_on_every_release_including_565_77() {
        let want = [
            ((535, 129, 3), None, None),
            ((565, 77, 0), Some(60), Some(61)),
            ((580, 178, 4), Some(61), Some(62)),
            ((595, 71, 5), Some(60), Some(61)),
            ((595, 104, 2), Some(60), Some(61)),
            ((610, 57, 4), Some(60), Some(61)),
            ((615, 71, 9), Some(59), Some(60)),
        ];
        for ((a, b, p), en, dis) in want {
            let c = select(DriverVersion::new(a, b, p)).unwrap();
            assert_eq!(
                (c.enable_vblank_sem_control, c.disable_vblank_sem_control),
                (en, dis)
            );
            if let Some(en) = en {
                assert_eq!(
                    verdict(Some(DriverVersion::new(a, b, p)), en),
                    Verdict::AnswerVblank { reply_handle: true }
                );
                // SET_FLIPLOCK_GROUP sits just before ENABLE and is a modeset.
                assert_eq!(
                    verdict(Some(DriverVersion::new(a, b, p)), en - 1),
                    Verdict::Refuse
                );
            }
            if let Some(dis) = dis {
                assert_eq!(
                    verdict(Some(DriverVersion::new(a, b, p)), dis),
                    Verdict::AnswerVblank {
                        reply_handle: false
                    }
                );
            }
        }
    }

    /// The guest driver (conduit_gpu.c `nvgpu_nvkms_register_surface`) still
    /// picks REGISTER_SURFACE by version range: 17 for 580..615, else 16. It
    /// must agree with every table until it takes its number from one.
    #[test]
    fn the_guest_range_rule_agrees_with_every_table() {
        for (v, c) in all() {
            let guest = if v.major >= 580 && v.major < 615 {
                17
            } else {
                16
            };
            assert_eq!(c.register_surface, guest, "{v}");
        }
    }

    #[test]
    fn a_release_with_no_table_serves_only_the_first_two_commands() {
        let unknown = Some(DriverVersion::new(570, 86, 15));
        assert!(select(unknown.unwrap()).is_none());
        assert_eq!(verdict(unknown, 0), Verdict::Forward);
        assert_eq!(verdict(unknown, 1), Verdict::Forward);
        for cmd in 2..80 {
            assert_eq!(verdict(unknown, cmd), Verdict::Refuse, "{cmd}");
            assert_eq!(verdict(None, cmd), Verdict::Refuse, "{cmd}");
        }
        // Nor a neighbour's table: 565.78 is not 565.77.
        assert!(select(DriverVersion::new(565, 78, 0)).is_none());
    }

    #[test]
    fn query_disp_and_registration_are_told_apart() {
        let v = Some(DriverVersion::new(565, 77, 0));
        assert_eq!(verdict(v, 2), Verdict::AnswerQueryDisp);
        assert_eq!(verdict(v, 16), Verdict::ForwardWithFd);
        for cmd in [17, 18, 19, 20, 0, 1] {
            assert_eq!(verdict(v, cmd), Verdict::Forward, "{cmd}");
        }
        // SET_MODE and friends.
        for cmd in [3, 7, 10, 21, 59] {
            assert_eq!(verdict(v, cmd), Verdict::Refuse, "{cmd}");
        }
    }
}
