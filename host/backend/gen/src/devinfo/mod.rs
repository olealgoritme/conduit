//! `DRM_NVIDIA_GET_DEV_INFO`: what a DRM node is, in the release's own words.
//!
//! nvidia-drm answers this ioctl with a struct of `u32`s, and the struct is
//! not the same in every release. The ioctl number carries its size, and the
//! words move:
//!
//! | release | bytes | words |
//! |---|---|---|
//! | 535.129.03 | 20 | gpu_id, primary_index, kind, generation, sector layout |
//! | 565.77 .. 570 | 32 | + supports_alloc, supports_sync_fd, supports_semsurf |
//! | 575 and later | 36 | + mig_device, second |
//!
//! Read as the newest layout, a 565 answer has every word after the first
//! one place off: the generation taken for the page kind, the sector layout
//! for the generation, and so a block-linear modifier built from them names a
//! layout the card does not use.
//!
//! One rule keeps that out of the rest of the code: **the layout is the
//! release's, and nothing else knows it.** The backend decodes the host's
//! answer once, through [`Layout::decode`], into a [`DevInfo`] whose fields
//! have names. It hands the guest [`DevInfo::to_wire`], a record in one fixed
//! order whatever the host is. The guest encodes that record again for
//! whatever size its own caller's ioctl asks for (`guest/linux/devinfo/`,
//! generated from the same probe), and never writes more than that size.
//!
//! Generated by `gen/devinfo_extract.py`: every offset is an `offsetof`.

pub mod v535_129_03;
pub mod v565_77_00;
pub mod v580_178_04;
pub mod v595_104_02;
pub mod v595_71_05;
pub mod v610_57_04;
pub mod v615_71_09;

use crate::version::DriverVersion;

/// One field of the ioctl's answer.
///
/// The discriminant is the field's word in the wire record
/// ([`DevInfo::to_wire`]), which is the newest release's order. That is also
/// `enum nvgpu_di_field` in `guest/linux/nvgpu_devinfo.h`, which a test here
/// holds to this order.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Field {
    GpuId,
    MigDevice,
    PrimaryIndex,
    SupportsAlloc,
    GenericPageKind,
    PageKindGeneration,
    SectorLayout,
    SupportsSyncFd,
    SupportsSemsurf,
}

/// Number of fields: the words of the wire record.
pub const FIELDS: usize = 9;

impl Field {
    pub const ALL: [Field; FIELDS] = [
        Field::GpuId,
        Field::MigDevice,
        Field::PrimaryIndex,
        Field::SupportsAlloc,
        Field::GenericPageKind,
        Field::PageKindGeneration,
        Field::SectorLayout,
        Field::SupportsSyncFd,
        Field::SupportsSemsurf,
    ];
}

/// A DRM node's answer, with names. Fields a release does not have are zero.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct DevInfo {
    /// The NVIDIA gpu id: what a userspace driver matches a DRM node to an RM
    /// device by.
    pub gpu_id: u32,
    pub mig_device: u32,
    /// The node's card number (`card%d`).
    pub primary_index: u32,
    pub supports_alloc: u32,
    /// `generic_page_kind`, `page_kind_generation` and `sector_layout`: what a
    /// block-linear modifier encodes besides the block height. GB202 answers
    /// 0x06, 2, 1.
    pub generic_page_kind: u32,
    pub page_kind_generation: u32,
    pub sector_layout: u32,
    pub supports_sync_fd: u32,
    pub supports_semsurf: u32,
}

impl DevInfo {
    pub fn get(&self, f: Field) -> u32 {
        self.to_wire()[f as usize]
    }

    /// The record the backend gives the guest: one word per [`Field`], in
    /// that order, for every host release.
    pub fn to_wire(&self) -> [u32; FIELDS] {
        [
            self.gpu_id,
            self.mig_device,
            self.primary_index,
            self.supports_alloc,
            self.generic_page_kind,
            self.page_kind_generation,
            self.sector_layout,
            self.supports_sync_fd,
            self.supports_semsurf,
        ]
    }

    pub fn from_wire(w: [u32; FIELDS]) -> Self {
        Self {
            gpu_id: w[0],
            mig_device: w[1],
            primary_index: w[2],
            supports_alloc: w[3],
            generic_page_kind: w[4],
            page_kind_generation: w[5],
            sector_layout: w[6],
            supports_sync_fd: w[7],
            supports_semsurf: w[8],
        }
    }
}

/// Where one release keeps each field.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Layout {
    /// `sizeof(struct drm_nvidia_get_dev_info_params)`.
    pub size: usize,
    /// Byte offset of each [`Field`], or `None` where the release has none.
    pub at: [Option<usize>; FIELDS],
}

impl Layout {
    /// `DRM_IOCTL_NVIDIA_GET_DEV_INFO` for this release:
    /// `_IOWR('d', DRM_COMMAND_BASE + DRM_NVIDIA_GET_DEV_INFO, params)`, i.e.
    /// direction read|write, this many bytes, type 'd', nr 0x43. It differs
    /// between releases for no reason but the size.
    pub const fn ioctl(&self) -> u32 {
        0xC000_6443 | ((self.size as u32) << 16)
    }

    /// Read the host's answer into named fields. `None` when `p` is shorter
    /// than the release's struct, which nothing would have written in full.
    pub fn decode(&self, p: &[u8]) -> Option<DevInfo> {
        if p.len() < self.size {
            return None;
        }
        let mut w = [0u32; FIELDS];
        for (word, at) in w.iter_mut().zip(self.at) {
            if let Some(at) = at {
                *word = u32::from_le_bytes(p[at..at + 4].try_into().unwrap());
            }
        }
        Some(DevInfo::from_wire(w))
    }

    /// Write `d` as this release's struct into `out`, which is what a caller
    /// of this release's ioctl would hand over: a field the release has is
    /// written, one it lacks is not, and nothing is written past `out`. The
    /// number of bytes the release's struct covers is returned (`out` is
    /// shorter than that only when the caller's buffer is, and then the
    /// fields that do not fit are dropped, not truncated mid-word).
    pub fn encode(&self, d: &DevInfo, out: &mut [u8]) -> usize {
        let w = d.to_wire();
        for (word, at) in w.iter().zip(self.at) {
            if let Some(at) = at
                && let Some(dst) = out.get_mut(at..at + 4)
            {
                dst.copy_from_slice(&word.to_le_bytes());
            }
        }
        self.size
    }
}

struct Profile {
    version: DriverVersion,
    layout: fn() -> Layout,
}

/// Profiles in ascending version order.
static PROFILES: &[Profile] = &[
    Profile {
        version: DriverVersion::new(535, 129, 3),
        layout: || v535_129_03::LAYOUT,
    },
    Profile {
        version: DriverVersion::new(565, 77, 0),
        layout: || v565_77_00::LAYOUT,
    },
    Profile {
        version: DriverVersion::new(580, 178, 4),
        layout: || v580_178_04::LAYOUT,
    },
    Profile {
        version: DriverVersion::new(595, 71, 5),
        layout: || v595_71_05::LAYOUT,
    },
    Profile {
        version: DriverVersion::new(595, 104, 2),
        layout: || v595_104_02::LAYOUT,
    },
    Profile {
        version: DriverVersion::new(610, 57, 4),
        layout: || v610_57_04::LAYOUT,
    },
    Profile {
        version: DriverVersion::new(615, 71, 9),
        layout: || v615_71_09::LAYOUT,
    },
];

/// The layout of one host release.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Selected {
    pub layout: Layout,
    /// The host release has a table of its own. When false this is an older
    /// release's, and the struct may have grown since: 565 to 575 added a
    /// word and moved the rest.
    pub exact: bool,
}

/// The layout for a host driver version: its own, or the nearest older one.
pub fn select(v: DriverVersion) -> Option<Selected> {
    PROFILES
        .iter()
        .rev()
        .find(|p| p.version <= v)
        .map(|p| Selected {
            layout: (p.layout)(),
            exact: p.version == v,
        })
}

/// The releases that have a layout.
pub fn supported_versions() -> impl Iterator<Item = DriverVersion> {
    PROFILES.iter().map(|p| p.version)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn words(w: &[u32]) -> Vec<u8> {
        w.iter().flat_map(|x| x.to_le_bytes()).collect()
    }

    /// What a 565.77 host answers for an RTX 4070 SUPER on card1: eight
    /// words, no `mig_device`. Read as nine they come out as kind 2 and
    /// generation 1, which is the bug this table exists to prevent.
    #[test]
    fn a_565_answer_is_read_as_565_writes_it() {
        let host = words(&[0x200, 1, 1, 6, 2, 1, 1, 1]);
        let got = select(DriverVersion::new(565, 77, 0))
            .unwrap()
            .layout
            .decode(&host)
            .unwrap();
        assert_eq!(
            got,
            DevInfo {
                gpu_id: 0x200,
                mig_device: 0,
                primary_index: 1,
                supports_alloc: 1,
                generic_page_kind: 6,
                page_kind_generation: 2,
                sector_layout: 1,
                supports_sync_fd: 1,
                supports_semsurf: 1,
            }
        );
    }

    /// The same bytes under the old, only layout: the wrong page kind and
    /// generation. Holds that the two layouts really are different.
    #[test]
    fn the_565_words_read_as_575_are_the_bug() {
        let host = words(&[0x200, 1, 1, 6, 2, 1, 1, 1, 0]);
        let wrong = v580_178_04::LAYOUT.decode(&host).unwrap();
        assert_eq!(
            (wrong.generic_page_kind, wrong.page_kind_generation),
            (2, 1)
        );
    }

    /// A 9-word host: gpu_id, mig_device, primary_index, supports_alloc, kind,
    /// generation, sector layout, sync_fd, semsurf. Behaviour on every release
    /// that had this layout from the start is the reason the wire record is in
    /// this order.
    #[test]
    fn a_nine_word_answer_is_the_wire_record() {
        let host = words(&[0x100, 0, 0, 1, 6, 2, 1, 1, 1]);
        for v in [
            DriverVersion::new(580, 178, 4),
            DriverVersion::new(595, 71, 5),
            DriverVersion::new(595, 104, 2),
            DriverVersion::new(610, 57, 4),
            DriverVersion::new(615, 71, 9),
        ] {
            let d = select(v).unwrap().layout.decode(&host).unwrap();
            let wire = d.to_wire();
            assert_eq!(wire.to_vec(), vec![0x100, 0, 0, 1, 6, 2, 1, 1, 1], "{v}");
        }
    }

    #[test]
    fn a_535_answer_has_no_capability_words() {
        let host = words(&[0x100, 0, 0xfe, 0, 1]);
        let d = select(DriverVersion::new(535, 129, 3))
            .unwrap()
            .layout
            .decode(&host)
            .unwrap();
        assert_eq!(d.gpu_id, 0x100);
        assert_eq!(d.generic_page_kind, 0xfe);
        assert_eq!(d.sector_layout, 1);
        assert_eq!(
            (d.supports_alloc, d.supports_sync_fd, d.mig_device),
            (0, 0, 0)
        );
    }

    #[test]
    fn a_short_answer_decodes_to_nothing() {
        let l = v580_178_04::LAYOUT;
        assert!(l.decode(&[0u8; 35]).is_none());
        assert!(l.decode(&[0u8; 36]).is_some());
    }

    /// The ioctl number is `_IOWR('d', 0x43, params)`; the size is in it.
    #[test]
    fn the_ioctl_number_carries_the_release_s_size() {
        assert_eq!(v580_178_04::LAYOUT.ioctl(), 0xC024_6443);
        assert_eq!(v565_77_00::LAYOUT.ioctl(), 0xC020_6443);
        assert_eq!(v535_129_03::LAYOUT.ioctl(), 0xC014_6443);
    }

    /// A caller's buffer is never written past. A 32-byte caller of a
    /// 36-byte answer would have lost four bytes of its stack to the
    /// `mig_device` word's neighbour.
    #[test]
    fn encoding_never_writes_past_the_callers_buffer() {
        let d = DevInfo::from_wire([1, 2, 3, 4, 5, 6, 7, 8, 9]);
        // A canary-bordered buffer the size of the 565 struct.
        let mut buf = vec![0xAAu8; 32 + 8];
        v565_77_00::LAYOUT.encode(&d, &mut buf[..32]);
        assert!(buf[32..].iter().all(|&b| b == 0xAA), "wrote past 32 bytes");
        // And what it wrote reads back.
        assert_eq!(
            v565_77_00::LAYOUT.decode(&buf[..32]).unwrap(),
            DevInfo { mig_device: 0, ..d }
        );

        // The newest layout into a buffer too small for its last words: those
        // are dropped whole.
        let mut small = vec![0xAAu8; 30];
        v580_178_04::LAYOUT.encode(&d, &mut small);
        assert_eq!(small.len(), 30);
        assert_eq!(&small[24..28], &7u32.to_le_bytes());
        assert_eq!(&small[28..], &[0xAA, 0xAA], "a half word is not written");
    }

    /// Round trip through every release: what a release's struct has
    /// survives, and what it lacks is zero.
    #[test]
    fn every_release_round_trips_the_fields_it_has() {
        let d = DevInfo::from_wire([0x200, 11, 1, 1, 6, 2, 1, 1, 1]);
        for p in PROFILES {
            let l = (p.layout)();
            let mut buf = vec![0u8; l.size];
            assert_eq!(l.encode(&d, &mut buf), l.size);
            let back = l.decode(&buf).unwrap();
            for f in Field::ALL {
                let want = if l.at[f as usize].is_some() {
                    d.get(f)
                } else {
                    0
                };
                assert_eq!(back.get(f), want, "{} {:?}", p.version, f);
            }
        }
    }

    /// The guest picks the layout by the size its caller's ioctl carries, so
    /// two releases of one size must be the same layout.
    #[test]
    fn a_size_names_one_layout() {
        for a in PROFILES {
            for b in PROFILES {
                let (la, lb) = ((a.layout)(), (b.layout)());
                if la.size == lb.size {
                    assert_eq!(la, lb, "{} and {} share a size", a.version, b.version);
                }
            }
        }
    }

    #[test]
    fn every_layout_is_inside_its_struct_and_has_the_words_every_release_has() {
        for p in PROFILES {
            let l = (p.layout)();
            for f in [
                Field::GpuId,
                Field::PrimaryIndex,
                Field::GenericPageKind,
                Field::PageKindGeneration,
                Field::SectorLayout,
            ] {
                assert!(l.at[f as usize].is_some(), "{} lacks {:?}", p.version, f);
            }
            let mut seen = vec![];
            for at in l.at.iter().flatten() {
                assert!(at % 4 == 0 && at + 4 <= l.size, "{}", p.version);
                assert!(!seen.contains(at), "{} overlaps", p.version);
                seen.push(*at);
            }
            assert_eq!(
                seen.len() * 4,
                l.size,
                "{}: a word nothing names",
                p.version
            );
        }
    }

    #[test]
    fn a_release_older_than_every_table_has_none() {
        assert!(select(DriverVersion::new(470, 0, 0)).is_none());
        // 570 is between tables: the nearest older (565.77, 32 bytes) is also
        // right for it, and says it is not its own.
        let s = select(DriverVersion::new(570, 86, 15)).unwrap();
        assert!(!s.exact);
        assert_eq!(s.layout.size, 32);
        assert!(select(DriverVersion::new(565, 77, 0)).unwrap().exact);
    }

    /// `guest/linux/nvgpu_devinfo.h` names the same words in the same order.
    #[test]
    fn the_guests_field_enum_is_this_order() {
        let h = std::fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../../guest/linux/nvgpu_devinfo.h"
        ))
        .expect("the guest header");
        let start = h.find("enum nvgpu_di_field {").expect("the enum");
        let body = &h[start..start + h[start..].find("};").unwrap()];
        let names: Vec<&str> = body
            .lines()
            .filter_map(|l| l.trim().strip_prefix("NVGPU_DI_"))
            .filter_map(|l| l.split([',', ' ', '=']).next())
            .filter(|n| *n != "FIELDS" && *n != "ABSENT")
            .collect();
        let ours: Vec<String> = Field::ALL
            .iter()
            .map(|f| format!("{f:?}").to_uppercase())
            .collect();
        let theirs: Vec<String> = names.iter().map(|n| n.replace('_', "")).collect();
        assert_eq!(theirs, ours);
        assert_eq!(names.len(), FIELDS);
    }
}
