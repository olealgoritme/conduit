#!/usr/bin/env python3
"""Generate where one release keeps each field of nvidia-drm's GET_DEV_INFO.

`DRM_IOCTL_NVIDIA_GET_DEV_INFO` answers what a DRM node is: the NVIDIA gpu id,
the node's card number, and how the card lays memory out (page kind,
generation, sector layout) plus what the node serves (alloc, sync fd,
semaphore surfaces). Its parameter struct is not the same in every release,
and the ioctl number carries its size:

    535.129.03       20 bytes   no supports_* words, no mig_device
    565.77 - 570     32 bytes   supports_alloc, supports_sync_fd, supports_semsurf
    575 and later    36 bytes   mig_device, second word

Read as the newest layout, a 565 answer has every word from the second on one
place off: the backend took generation for the page kind and the sector
layout for the generation. So the layout is generated per release, like every
other table here, from a compiler's `sizeof` and `offsetof` over the release's
own struct -- not from a count of lines.

    ./devinfo_extract.py --ogkm ~/forks/ogkm-565.77 --version 565.77 \\
        > src/devinfo/v565_77_00.rs
    ./devinfo_extract.py --ogkm ... --version 565.77 --lang c \\
        > ../../../guest/linux/devinfo/v565_77_00.h

A member this script has no name for stops it: a release that adds a field
needs a person to say what the field means before anything reads it.

Needs: python3, cc.
"""

import argparse
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile

# The fields, in the order of the wire record the backend sends the guest
# (and `abi::devinfo::Field`, and `enum nvgpu_di_field` in nvgpu_devinfo.h):
# the 575+ order, which is the newest, so a release with fewer words is this
# list with holes. Add to the end only.
FIELDS = [
    "gpu_id",
    "mig_device",
    "primary_index",
    "supports_alloc",
    "generic_page_kind",
    "page_kind_generation",
    "sector_layout",
    "supports_sync_fd",
    "supports_semsurf",
]

# The words every release has. A struct without them is not the one this
# backend knows how to read.
REQUIRED = ["gpu_id", "primary_index", "generic_page_kind", "page_kind_generation", "sector_layout"]

# Where the header lives: renamed once, between 580 and 595.
HEADERS = [
    "kernel-open/nvidia-drm/nvidia-drm-ioctl.h",
    "kernel-open/nvidia-drm/nv_drm_common_ioctl.h",
]

STRUCT = re.compile(r"struct\s+drm_nvidia_get_dev_info_params\s*\{(.*?)\n\};", re.S)
MEMBER = re.compile(r"^\s*(\w+)\s+(\w+)\s*;", re.M)


def read_struct(ogkm):
    for h in HEADERS:
        path = os.path.join(ogkm, h)
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8", errors="replace").read()
        m = STRUCT.search(text)
        if m:
            return m.group(0), m.group(1)
    sys.exit("no drm_nvidia_get_dev_info_params in %s" % " or ".join(HEADERS))


def members(body):
    # Comments carry words like "uint32_t foo;" in prose; take them out first.
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    out = []
    for ty, name in MEMBER.findall(body):
        if ty != "uint32_t":
            sys.exit(f"member {name} is {ty}, not uint32_t: the wire record is words")
        if name not in FIELDS:
            sys.exit(f"member {name} has no meaning here yet: add it to FIELDS (devinfo_extract.py)")
        out.append(name)
    return out


def probe(struct_text, names, cc):
    src = "#include <stddef.h>\n#include <stdint.h>\n#include <stdio.h>\n"
    src += struct_text + "\n"
    src += "int main(void) {\n"
    src += '  printf("size %zu\\n", sizeof(struct drm_nvidia_get_dev_info_params));\n'
    for n in names:
        src += '  printf("%s %%zu\\n", offsetof(struct drm_nvidia_get_dev_info_params, %s));\n' % (n, n)
    src += "  return 0;\n}\n"
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, "devinfo.c")
        open(c, "w").write(src)
        exe = os.path.join(d, "devinfo")
        r = subprocess.run([cc, "-w", c, "-o", exe], capture_output=True, text=True)
        if r.returncode:
            sys.stderr.write(r.stderr[-4000:])
            sys.exit("the GET_DEV_INFO probe did not compile")
        out = subprocess.run([exe], capture_output=True, text=True, check=True).stdout
    v = {}
    for ln in out.splitlines():
        k, n = ln.split()
        v[k] = int(n)
    return v


def emit_rust(v, version, stream):
    w = stream.write
    ident = version.replace(".", "_")
    w("// Generated by gen/devinfo_extract.py -- do not edit by hand.\n//\n")
    w("//   ./devinfo_extract.py --ogkm <open-gpu-kernel-modules at %s> \\\n" % version)
    w("//       --version %s > src/devinfo/v%s.rs\n//\n" % (version, ident))
    w("// Where driver %s keeps each field of `DRM_NVIDIA_GET_DEV_INFO`.\n\n" % version)
    w("use super::Layout;\n\n")
    w("pub static LAYOUT: Layout = Layout {\n")
    w("    size: %d,\n" % v["size"])
    w("    at: [\n")
    for f in FIELDS:
        w("        %s,\n" % ("Some(%d)" % v[f] if f in v else "None"))
    w("    ],\n};\n")


def emit_c(v, version, stream):
    w = stream.write
    ident = version.replace(".", "_")
    w("/* SPDX-License-Identifier: GPL-2.0 */\n/*\n")
    w(" * Generated by gen/devinfo_extract.py -- do not edit by hand.\n *\n")
    w(" *   ./devinfo_extract.py --ogkm <open-gpu-kernel-modules at %s> \\\n" % version)
    w(" *       --version %s --lang c > guest/linux/devinfo/v%s.h\n *\n" % (version, ident))
    w(" * Where driver %s keeps each field of DRM_NVIDIA_GET_DEV_INFO.\n" % version)
    w(" * See nvgpu_devinfo.h.\n */\n\n")
    w("static const struct nvgpu_devinfo_layout nvgpu_devinfo_v%s = {\n" % ident)
    w("\t.size = %d,\n" % v["size"])
    w("\t.at = {\n")
    for f in FIELDS:
        w("\t\t[NVGPU_DI_%s] = %s,\n" % (f.upper(), v[f] if f in v else "NVGPU_DI_ABSENT"))
    w("\t},\n};\n")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--ogkm", required=True, help="open-gpu-kernel-modules checkout at the release tag")
    ap.add_argument("--version", required=True)
    ap.add_argument("--lang", choices=["rust", "c"], default="rust")
    ap.add_argument("--cc", default=os.environ.get("CC", "cc"))
    a = ap.parse_args()

    text, body = read_struct(a.ogkm)
    names = members(body)
    for r in REQUIRED:
        if r not in names:
            sys.exit(f"the struct has no {r}")
    v = probe(text, names, a.cc)

    # Words, back to back: the wire record and the decoder both index by
    # offset / 4, and a pad or a 64-bit member would break the reading of every
    # field after it.
    if v["size"] != 4 * len(names) or any(v[n] != 4 * i for i, n in enumerate(names)):
        sys.exit("the struct is not a plain run of u32s: %r" % v)
    # The order the wire carries is FIELDS' order; a release that reorders the
    # words it has is a different layout, and says so in its offsets.

    buf = io.StringIO()
    (emit_c if a.lang == "c" else emit_rust)(v, a.version, buf)
    text = buf.getvalue()
    if a.lang == "rust" and shutil.which("rustfmt"):
        r = subprocess.run(
            [shutil.which("rustfmt"), "--edition", "2024"], input=text, capture_output=True, text=True
        )
        if r.returncode == 0:
            text = r.stdout
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
