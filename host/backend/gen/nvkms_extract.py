#!/usr/bin/env python3
"""Generate the NVKMS command numbers of one release.

`/dev/nvidia-modeset` multiplexes every operation through one ioctl number;
the command sits in the first word of the request, as an index into
`enum NvKmsIoctlCommand` (nvkms-api.h). NVKMS is the host's real display
driver, shared with the host compositor, so the backend serves a guest only
the commands buffer sharing needs and refuses the rest. To name them it needs
their numbers, and those move: REGISTER_SURFACE is 16 on 535, 17 on 580..610
and 16 on 615; ENABLE_VBLANK_SEM_CONTROL is 60 on 565.77, 61 on 580.178.04
and absent on 535, because entries are added in the middle of the enum.

    ./nvkms_extract.py --ogkm ~/forks/ogkm-615.71.09 --version 615.71.09 \\
        > src/nvkms/v615_71_09.rs

Every entry of the enum is emitted with the value a probe compiled against the
release's own header prints; nothing is counted or offset from another entry.
A command the backend names (the `REQUIRED` and `OPTIONAL` lists below) that the
release lacks stops the script, unless it is optional, in which case the table
says it is absent and the backend refuses it.

Needs: python3, cc.
"""

import argparse
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile

HEADER = "src/nvidia-modeset/interface/nvkms-api.h"
INCS = [
    "src/nvidia-modeset/interface",
    "src/common/sdk/nvidia/inc",
    "src/common/inc",
    "src/common/unix/common/inc",
]

# Commands the backend serves or answers, as (enum name without the prefix,
# field of `Commands`). The first group exists in every release.
REQUIRED = [
    ("ALLOC_DEVICE", "alloc_device"),
    ("FREE_DEVICE", "free_device"),
    ("QUERY_DISP", "query_disp"),
    ("REGISTER_SURFACE", "register_surface"),
    ("UNREGISTER_SURFACE", "unregister_surface"),
    ("GRANT_SURFACE", "grant_surface"),
    ("ACQUIRE_SURFACE", "acquire_surface"),
    ("RELEASE_SURFACE", "release_surface"),
]
# Added after 535.
OPTIONAL = [
    ("ENABLE_VBLANK_SEM_CONTROL", "enable_vblank_sem_control"),
    ("DISABLE_VBLANK_SEM_CONTROL", "disable_vblank_sem_control"),
]


def enum_names(ogkm):
    text = open(os.path.join(ogkm, HEADER)).read()
    m = re.search(r"enum\s+NvKmsIoctlCommand\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit("no enum NvKmsIoctlCommand in " + HEADER)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    if re.search(r"^\s*#", body, re.M):
        sys.exit("the enum has preprocessor conditionals; read it by hand")
    names = []
    for item in body.split(","):
        item = item.strip()
        if not item:
            continue
        n = item.split("=")[0].strip()
        if not n.startswith("NVKMS_IOCTL_"):
            sys.exit(f"unexpected enumerator {n!r}")
        names.append(n[len("NVKMS_IOCTL_"):])
    return names


def probe(ogkm, names):
    src = ['#include "nvkms-api.h"', "#include <stdio.h>", "int main(void) {"]
    for n in names:
        src.append(f'  printf("%s %d\\n", "{n}", (int)NVKMS_IOCTL_{n});')
    src.append("  return 0;\n}")
    incs = [x for i in INCS for x in ("-I", os.path.join(ogkm, i))]
    with tempfile.TemporaryDirectory() as d:
        c, exe = os.path.join(d, "nvkms.c"), os.path.join(d, "nvkms")
        open(c, "w").write("\n".join(src))
        r = subprocess.run(["cc", "-w", *incs, c, "-o", exe], capture_output=True, text=True)
        if r.returncode:
            sys.stderr.write(r.stderr[-4000:])
            sys.exit("the probe did not compile")
        out = subprocess.run([exe], capture_output=True, text=True, check=True).stdout
    return {k: int(v) for k, v in (ln.split() for ln in out.splitlines() if ln.strip())}


def emit(values, version, stream):
    w = stream.write
    mod = "v" + version.replace(".", "_")
    w("// Generated by gen/nvkms_extract.py -- do not edit by hand.\n//\n")
    w(f"//   ./nvkms_extract.py --ogkm <open-gpu-kernel-modules at {version}> \\\n")
    w(f"//       --version {version} > src/nvkms/{mod}.rs\n//\n")
    w(f"// The NVKMS command numbers of driver {version}.\n\n")
    w("use super::Commands;\n\n")
    w("pub static COMMANDS: Commands = Commands {\n")
    for name, field in REQUIRED:
        w(f"    {field}: {values[name]},\n")
    for name, field in OPTIONAL:
        v = values.get(name)
        w(f"    {field}: {'None' if v is None else f'Some({v})'},\n")
    w("    all: &[\n")
    for n, v in sorted(values.items(), key=lambda kv: kv[1]):
        w(f'        ("{n}", {v}),\n')
    w("    ],\n};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ogkm", required=True, help="open-gpu-kernel-modules checkout at the release tag")
    ap.add_argument("--version", required=True)
    a = ap.parse_args()

    names = enum_names(a.ogkm)
    values = probe(a.ogkm, names)
    if sorted(values.values()) != list(range(len(names))):
        sys.exit("the enum's values are not 0..N: an explicit value, read it by hand")
    for name, _ in REQUIRED:
        if name not in values:
            sys.exit(f"{a.version} has no NVKMS_IOCTL_{name}")

    buf = io.StringIO()
    emit(values, a.version, buf)
    text = buf.getvalue()
    fmt = shutil.which("rustfmt")
    if fmt:
        r = subprocess.run([fmt, "--edition", "2024"], input=text, capture_output=True, text=True)
        if r.returncode == 0:
            text = r.stdout
        else:
            sys.stderr.write("rustfmt refused this table; writing it unformatted\n")
    sys.stdout.write(text)
    absent = [n for n, _ in OPTIONAL if n not in values]
    sys.stderr.write(f"{a.version}: {len(names)} commands, absent: {', '.join(absent) or 'none'}\n")


if __name__ == "__main__":
    main()
