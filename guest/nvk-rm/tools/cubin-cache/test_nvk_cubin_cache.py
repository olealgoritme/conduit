def lz4_literals(data):
    """An LZ4 block made of one literal run (valid, if not small)."""
    n = len(data)
    if n < 15:
        return bytes([n << 4]) + data
    out = bytearray([0xF0])
    rest = n - 15
    while rest >= 255:
        out.append(255)
        rest -= 255
    out.append(rest)
    return bytes(out) + data


def fatbin_entry(kind, sm, payload, flags=0, decompressed=0, compressed=0):
    hdr = struct.pack("<HHIQIIHHIIIQQQ", kind, 0x0101, 64, len(payload),
                      compressed, 0, 0, 0, sm, 0, 0, flags, 0, decompressed)
    assert len(hdr) == 64
    return hdr + payload


def fatbin(*entries):
    body = b"".join(entries)
    return struct.pack("<IHHQ", ncc.FATBIN_MAGIC, 1, 16, len(body)) + body


def cubin(sm, sections):
    """A CUDA ELF64 with the given (name, type, data, info, link, entsize)
    sections after the null section; a .shstrtab is appended."""
    names = b"\0"
    offs = []
    for s in sections:
        offs.append(len(names))
        names += s[0].encode() + b"\0"
    shstr_name = len(names)
    names += b".shstrtab\0"
    allsec = list(sections) + [(".shstrtab", 3, names, 0, 0, 0)]
    noffs = offs + [shstr_name]
    data = bytearray(64)
    places = []
    for s in allsec:
        while len(data) % 8:
            data.append(0)
        places.append(len(data))
        if s[1] != 8:
            data += s[2]
    while len(data) % 8:
        data.append(0)
    shoff = len(data)
    data += bytes(64)                   # null section
    for s, no, pl in zip(allsec, noffs, places):
        size = len(s[2]) if s[1] != 8 else s[2]
        data += struct.pack("<IIQQQQIIQQ", no, s[1], 0, 0, pl, size, s[4], s[3], 1, s[5])
    ident = b"\x7fELF" + bytes([2, 1, 1, 0x41, 8]) + bytes(7)
    hdr = ident + struct.pack("<HHIQQQIHHHHHH", 2, ncc.EM_CUDA, 1, 0, 0, shoff,
                              sm << 8, 64, 0, 0, 64, len(allsec) + 1, len(allsec))
    data[:64] = hdr
    return bytes(data)


def sym(name_off, shndx, value, size, info=0x11):
    return struct.pack("<IBBHQQ", name_off, info, 0, shndx, value, size)


def dlss_like_cubin(sm, reloc_type=2, text_reloc=False, reloc_sym=2):
    """A kernel, bank 4 with one R_CUDA_64 to a global, an empty
    .rela.text as sm_90+ cubins have, and .rel.debug_frame."""
    strtab = b"\0k\0G\0"
    secs = [
        (".text.k", 1, bytes(128), 0, 0, 0),                 # 1
        (".nv.constant4", 1, bytes(16), 0, 0, 0),            # 2
        (".nv.global", 8, 8, 0, 0, 0),                       # 3 (NOBITS)
        (".strtab", 3, strtab, 0, 0, 0),                     # 4
        (".symtab", 2, bytes(24) + sym(1, 1, 0, 128, 0x12) + sym(3, 3, 0, 8), 0, 4, 24),  # 5
        (".rel.nv.constant4", 9, struct.pack("<QQ", 8, (reloc_sym << 32) | reloc_type), 2, 5, 16),  # 6
        (".rela.text.k", 4, b"" if not text_reloc else
         struct.pack("<QQq", 0, (2 << 32) | 2, 0), 1, 5, 24),          # 7
        (".debug_frame", 1, bytes(8), 0, 0, 0),              # 8
        (".rel.debug_frame", 9, struct.pack("<QQ", 0, (1 << 32) | 2), 8, 5, 16),  # 9
    ]
    return cubin(sm, secs)


class Blake3(unittest.TestCase):
    def test_official_vectors(self):
        for n, want in B3_VECTORS.items():
            data = bytes(i % 251 for i in range(n))
            self.assertEqual(ncc.blake3_digest(data).hex(), want, n)

    def test_hex_matches_digest(self):
        self.assertEqual(ncc.blake3_hex(b"abc"), ncc.blake3_digest(b"abc").hex())


class Lz4(unittest.TestCase):
    def test_literals(self):
        for n in (0, 1, 14, 15, 16, 300, 1000):
            data = bytes(range(256)) * 4
            data = data[:n]
            self.assertEqual(ncc.lz4_block_decompress(lz4_literals(data)), data)

    def test_overlapping_match(self):
        # "ab" then a match of 10 at offset 2, then the last literals "!"
        block = bytes([0x26]) + b"ab" + struct.pack("<H", 2) + bytes([0x10]) + b"!"
        self.assertEqual(ncc.lz4_block_decompress(block), b"ab" * 6 + b"!")

    def test_bad_offset(self):
        block = bytes([0x10]) + b"a" + struct.pack("<H", 5)
        with self.assertRaises(ncc.FatbinError):
            ncc.lz4_block_decompress(block)


class Fatbins(unittest.TestCase):
    def build(self):
        sass75 = dlss_like_cubin(75)
        comp = lz4_literals(PTX)
        fb = fatbin(fatbin_entry(ncc.KIND_SASS, 75, sass75),
                    fatbin_entry(ncc.KIND_PTX, 80, PTX),
                    fatbin_entry(ncc.KIND_PTX, 89, comp, flags=ncc.FLAG_COMPRESS_LZ4,
                                 decompressed=len(PTX), compressed=len(comp)))
        return fb, comp

    def test_find_and_parse(self):
        fb, comp = self.build()
        buf = b"MZ" + bytes(100) + fb + bytes(50) + b"\x50\xed\x55\xba junk"
        fbs, refused = ncc.find_fatbins(buf)
        self.assertEqual(len(fbs), 1)
        self.assertEqual(refused, 1)
        f = fbs[0]
        self.assertEqual(f.sass_sms(), [75])
        self.assertEqual(f.ptx_sms(), [80, 89])
        self.assertTrue(f.has_sass(75))
        self.assertFalse(f.has_sass(120))
        e = f.ptx_for(120)
        self.assertEqual(e.sm, 89)
        self.assertTrue(e.compressed)
        self.assertEqual(e.data(), PTX)
        # the key is over the bytes as stored, compressed here
        self.assertEqual(e.key(), ncc.blake3_hex(comp))
        self.assertEqual(f.ptx_for(85).sm, 80)
        self.assertIsNone(f.ptx_for(75))

    def test_truncated_fatbin_is_refused(self):
        fb, _ = self.build()
        for cut in (8, 20, 40, len(fb) - 1):
            fbs, _ = ncc.find_fatbins(fb[:cut])
            self.assertEqual(fbs, [], cut)


class Cubins(unittest.TestCase):
    def test_what_nvk_loads(self):
        info = ncc.parse_cubin(dlss_like_cubin(120))
        self.assertEqual(info.sm, 120)
        self.assertEqual(info.kernels, ["k"])
        self.assertEqual(info.cbanks, {4})
        self.assertEqual(info.globals_, [".nv.global"])
        self.assertEqual(info.relocs, 1)
        self.assertEqual(info.nvk_problems(), [])

    def test_code_addresses_in_bank_4(self):
        # position-independent code: bank 4 holds a subroutine's address
        info = ncc.parse_cubin(dlss_like_cubin(120, reloc_sym=1))
        self.assertEqual(info.relocs, 1)
        self.assertEqual(info.nvk_problems(), [])
        # a symbol in no section NVK places
        self.assertEqual(ncc.parse_cubin(dlss_like_cubin(120, reloc_sym=0)).nvk_problems(),
                         ["relocation against a symbol outside module data"])

    def test_what_nvk_refuses(self):
        self.assertEqual(ncc.parse_cubin(dlss_like_cubin(120, reloc_type=5)).nvk_problems(),
                         ["relocation type 5"])
        self.assertEqual(ncc.parse_cubin(dlss_like_cubin(120, text_reloc=True)).nvk_problems(),
                         ["relocations in text"])

    def test_not_cuda(self):
        with self.assertRaises(ncc.FatbinError):
            ncc.parse_cubin(b"\x7fELF" + bytes(60))


class FakeCompiler:
    def __init__(self, sm_out=None):
        self.calls = []
        self.sm_out = sm_out

    def compile(self, ptx, sm, name):
        self.calls.append((ptx, sm))
        return dlss_like_cubin(self.sm_out or sm)

    def close(self):
        pass


class Build(unittest.TestCase):
    def run_build(self, files, out, compiler, extra=()):
        orig = ncc.make_compiler
        ncc.make_compiler = lambda kind, ptxas: compiler
        try:
            return ncc.main(["build", "-o", out] + list(extra) + files)
        finally:
            ncc.make_compiler = orig

    def test_compiles_missing_sass_once(self):
        fb = fatbin(fatbin_entry(ncc.KIND_SASS, 89, dlss_like_cubin(89)),
                    fatbin_entry(ncc.KIND_PTX, 89, PTX))
        has120 = fatbin(fatbin_entry(ncc.KIND_SASS, 120, dlss_like_cubin(120)),
                        fatbin_entry(ncc.KIND_PTX, 89, PTX + b"x"))
        with tempfile.TemporaryDirectory() as d:
            dll = os.path.join(d, "nvngx_test.dll")
            with open(dll, "wb") as f:
                f.write(b"MZ" + fb + bytes(16) + has120 + fb)
            out = os.path.join(d, "cache")
            comp = FakeCompiler()
            self.assertEqual(self.run_build([dll], out, comp), 0)
            # the module with sm_120 SASS is left alone, the duplicate once
            self.assertEqual(len(comp.calls), 1)
            self.assertEqual(comp.calls[0], (PTX, 120))
            key = ncc.blake3_hex(PTX)
            self.assertTrue(os.path.exists(os.path.join(out, key + ".sm_120.cubin")))
            with open(os.path.join(out, "index.tsv")) as f:
                rows = [l.split("\t") for l in f if not l.startswith("#")]
            self.assertEqual(rows[0][:4], [key, "120", "89", "nvngx_test.dll"])
            # again: nothing to do
            comp2 = FakeCompiler()
            self.assertEqual(self.run_build([dll], out, comp2), 0)
            self.assertEqual(comp2.calls, [])

    def test_ptx_dump_and_text_key(self):
        with tempfile.TemporaryDirectory() as d:
            dump = os.path.join(d, "abc.ptx")
            with open(dump, "wb") as f:
                f.write(PTX + b"\0\0")
            out = os.path.join(d, "cache")
            self.assertEqual(self.run_build([dump], out, FakeCompiler()), 0)
            key = ncc.blake3_hex(PTX)
            self.assertTrue(os.path.exists(os.path.join(out, key + ".sm_120.cubin")))

    def test_wrong_sm_from_compiler_fails(self):
        fb = fatbin(fatbin_entry(ncc.KIND_PTX, 89, PTX))
        with tempfile.TemporaryDirectory() as d:
            dll = os.path.join(d, "a.dll")
            with open(dll, "wb") as f:
                f.write(fb)
            out = os.path.join(d, "cache")
            self.assertEqual(self.run_build([dll], out, FakeCompiler(sm_out=89)), 1)
            self.assertEqual([n for n in os.listdir(out) if n.endswith(".cubin")], [])


