#!/bin/sh
# Build dispcost for Linux (dispcost) and Windows x86_64 (dispcost.exe):
#
#   guest/nvk-rm/tools/dispcost/build.sh [OUT_DIR]
#
# dispcost_spv.h (the shader's three builds as SPIR-V words) is in the tree;
# with glslangValidator in PATH it is regenerated from dispcost.comp first.
# Needs a C compiler with the Vulkan headers and, for the .exe,
# x86_64-w64-mingw32-gcc (the .exe loads vulkan-1.dll at run time, so it
# needs no import library).
set -eu
here=$(cd "$(dirname "$0")" && pwd)
OUT=${1:-$here/out}
mkdir -p "$OUT"
if command -v glslangValidator > /dev/null; then
  tmp="$OUT/spv"
  mkdir -p "$tmp"
  glslangValidator -V --target-env vulkan1.1 -DSTEPS=0 --vn spv_tiny -o "$tmp/tiny.h" "$here/dispcost.comp" > /dev/null
  glslangValidator -V --target-env vulkan1.1 -DSTEPS=24 -DLD_EVERY=4 --vn spv_mid -o "$tmp/mid.h" "$here/dispcost.comp" > /dev/null
  glslangValidator -V --target-env vulkan1.1 -DSTEPS=110 -DLD_EVERY=4 --vn spv_big -o "$tmp/big.h" "$here/dispcost.comp" > /dev/null
  {
    echo "/* Generated by build.sh from dispcost.comp (glslangValidator -V): tiny STEPS=0,"
    echo " * mid STEPS=24 LD_EVERY=4, big STEPS=110 LD_EVERY=4 */"
    echo "#pragma once"
    grep -hvE '^[[:space:]]*(//|#pragma once)' "$tmp/tiny.h" "$tmp/mid.h" "$tmp/big.h"
  } > "$here/dispcost_spv.h"
fi
${CC:-cc} -O2 -Wall -I"$here" -o "$OUT/dispcost" "$here/dispcost.c" -lvulkan
if command -v x86_64-w64-mingw32-gcc > /dev/null; then
  # The Vulkan headers only, not the host's whole include directory
  VKINC=${VULKAN_INCLUDE:-/usr/include}
  mkdir -p "$OUT/inc"
  cp -r "$VKINC/vulkan" "$OUT/inc/"
  [ -d "$VKINC/vk_video" ] && cp -r "$VKINC/vk_video" "$OUT/inc/"
  x86_64-w64-mingw32-gcc -O2 -Wall -I"$here" -I"$here/../../tests" -I"$OUT/inc" -o "$OUT/dispcost.exe" "$here/dispcost.c" -static
fi
ls -la "$OUT"/dispcost*
