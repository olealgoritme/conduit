"""Generate names.h (class and control-command names) from the SDK headers of
NVIDIA's open kernel modules: gen-names.py <open-gpu-kernel-modules dir> > names.h"""
import glob, os, re, sys
inc = os.path.join(sys.argv[1], 'src/common/sdk/nvidia/inc')
cls = {}
for f in sorted(glob.glob(inc + '/class/cl*.h')):
    m = re.match(r'cl([0-9a-fA-F]+)\.h$', os.path.basename(f))
    if not m:
        continue
    num = int(m.group(1), 16)
    for line in open(f, errors='ignore'):
        mm = re.match(r'#define\s+([A-Z][A-Z0-9_]+)\s+\(?(0x[0-9a-fA-F]+)U?\)?', line)
        if mm and int(mm.group(2), 16) == num and not any(x in mm.group(1) for x in ('_CTRL', 'NOTIF', 'MESSAGE_ID')):
            cls.setdefault(num, mm.group(1))
ctl, weak = {}, {}
for f in sorted(glob.glob(inc + '/ctrl/**/*.h', recursive=True)):
    for line in open(f, errors='ignore'):
        mm = re.match(r'#define\s+([A-Z][A-Z0-9_]*_CTRL_[A-Z0-9_]+)\s+\(?(0x[0-9a-fA-F]+)U?\)?\s*(/\*.*)?$', line)
        if not mm or any(x in mm.group(1) for x in ('PARAMS', 'MESSAGE_ID', '_MAX', '_SIZE', '_NUM')):
            continue
        v = int(mm.group(2), 16)
        if '_CTRL_CMD_' in mm.group(1):
            if v > 0xffff or '/ctrl0000' in f:
                ctl.setdefault(v, mm.group(1))
        elif len(mm.group(2)) >= 10:
            weak.setdefault(v, mm.group(1))
for v, n in weak.items():
    ctl.setdefault(v, n)
print('/* generated by gen-names.py from the open-gpu-kernel-modules SDK headers */')
print('static const struct { unsigned v; const char *n; } cls_names[] = {')
for k in sorted(cls):
    print('  {0x%x, "%s"},' % (k, cls[k]))
print('};')
print('static const struct { unsigned v; const char *n; } ctl_names[] = {')
for k in sorted(ctl):
    print('  {0x%x, "%s"},' % (k, ctl[k]))
print('};')
