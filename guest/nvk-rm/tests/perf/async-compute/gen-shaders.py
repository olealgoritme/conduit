"""Embed SPIR-V files as C arrays: gen-shaders.py a.spv [b.spv ...] > shaders.h
(array name: file name with '.' -> '_', e.g. spin.comp.spv -> spin_comp_spv)"""
import os, sys
print('/* generated by gen-shaders.py */')
for path in sys.argv[1:]:
    data = open(path, 'rb').read()
    name = os.path.basename(path)[:-4].replace('.', '_') + '_spv'
    print('static const unsigned char %s[] = {' % name)
    for i in range(0, len(data), 16):
        print('  ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    print('};')
