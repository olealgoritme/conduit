#!/bin/sh
# Regenerates spin_sass.h: NAK's SM120 machine code for shader/spin.comp, one
# variant per output buffer (the output VA is a literal in the shader), from
# NVK's own pipeline creation on a faked GB202 (Mesa's nouveau drm-shim, the
# same way guest/nvk-rm/tools/nak-offline does).  No GPU is touched.
#
#   gen-spin.sh MESA_BUILD_DIR     (needs nvstats, the drm-shim and the devenv
#                                   ICD json built there; glslangValidator)
#
# The generated spin_sass.h is checked in next to the probe so building the
# probe needs none of this.
set -eu
B=$(cd "${1:?usage: gen-spin.sh MESA_BUILD_DIR}" && pwd)
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d "${TMPDIR:-/tmp}/gen-spin.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
export NOUVEAU_CHIPSET=1b2 NVK_UBO_DESC_CBUF=0 MESA_SHADER_CACHE_DISABLE=true NAK_DEBUG=print
ICD="$B/src/nouveau/vulkan/nouveau_devenv_icd.x86_64.json"
SHIM="$B/src/nouveau/drm-shim/libnouveau_noop_drm_shim.so"
OUT_VA_BASE=0x3000000000
OUT_VA_STRIDE=0x400000
NV=3
{
echo "/* Generated by gen-spin.sh (NAK, SM120): shader/spin.comp, $NV variants (OUT_VA = base + n * stride). */"
echo "#define SPIN_VARIANTS $NV"
echo "#define SPIN_OUT_VA_BASE ${OUT_VA_BASE}ull"
echo "#define SPIN_OUT_VA_STRIDE ${OUT_VA_STRIDE}ull"
for n in $(seq 0 $((NV - 1))); do
  va=$((OUT_VA_BASE + n * OUT_VA_STRIDE))
  glslangValidator -V --target-env vulkan1.3 -DOUT_VA_HI=$((va >> 32))u -DOUT_VA_LO=$((va & 0xffffffff))u \
      "$here/shader/spin.comp" -o "$tmp/spin$n.spv" >/dev/null
  (cd "$tmp" && VK_ICD_FILENAMES="$ICD" LD_PRELOAD="$SHIM" "$B/nvstats" "spin$n.spv" > "stats$n.txt" 2> "log$n.txt")
  python3 - "$tmp/log$n.txt" "$n" <<'PY'
import sys, re
log, n = sys.argv[1], sys.argv[2]
words, gprs, cur = [], None, None
for line in open(log, errors='replace'):
    if line.startswith('Num GPRs:'): gprs = int(line.split()[2])
    if line.startswith('Encoded shader:'): words = []; cur = words; continue
    if cur is not None:
        if line.startswith('  '): cur.extend(int(w, 16) for w in line.split())
        else: cur = None
assert words and gprs is not None, "no encoded shader in " + log
print(f"#define SPIN_GPRS_V{n} {gprs}")
print(f"static const uint32_t spin_code_v{n}[{len(words)}] = {{")
for i in range(0, len(words), 4):
    print("    " + ", ".join(f"0x{w:08x}" for w in words[i:i+4]) + ",")
print("};")
PY
done
} > "$here/spin_sass.h"
echo "wrote $here/spin_sass.h"
